#!/usr/bin/env python3
"""Generate the Darwin syscall number table from XNU's bsd/kern/syscalls.master.

Produces src/generated/syscalls.h with:
  - enum dsys_<name> = <number>   for every named (non-nosys) call
  - dsys_table_name[]             index -> canonical XNU name, for diagnostics

The master file is semicolon-comment FreeBSD style: lines beginning with ';' are
comments; '#if/#ifdef/#else/#endif' must be respected because it decides which
variant of a number is live (e.g. SOCKETS off means nosys).
"""
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "spec/master.txt"
OUT = sys.argv[2] if len(sys.argv) > 2 else "src/generated/syscalls.h"

# The master uses `#if SOCKETS` / `#if NATIVE_...`; for a userspace shim the
# correct configuration is everything enabled (SOCKETS=1, others=0).
DEFINES = {"SOCKETS": "1"}


def evaluate(expr, defines):
    expr = expr.strip()
    # handle simple identifiers and !identifier and defined(X)
    m = re.fullmatch(r"!\s*defined\s*\(\s*(\w+)\s*\)", expr)
    if m:
        return not (m.group(1) in defines)
    m = re.fullmatch(r"defined\s*\(\s*(\w+)\s*\)", expr)
    if m:
        return m.group(1) in defines
    m = re.fullmatch(r"!\s*(\w+)", expr)
    if m:
        v = defines.get(m.group(1))
        return not (v and v != "0")
    m = re.fullmatch(r"(\w+)", expr)
    if m:
        v = defines.get(m.group(1))
        return bool(v and v != "0")
    return True  # unknown expression: keep the block active


# prototype line:  <num> <AUE_...> <files> { <ret> name(args) ...; } [comment]
PROTO = re.compile(r"^(\d+)\s+(AUE_\w+)\s+([A-Z0-9_|]*)\s*\{(.*?)\}\s*(?:;(.*))?$")
CALL = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)\s*\(([^)]*)\)")


def main():
    stack = []  # list of (taken_now, any_taken, parent_active)
    active = True
    calls = {}

    with open(SRC, "r", encoding="utf-8", errors="replace") as f:
        for raw in f:
            line = raw.strip()
            if not line or line.startswith(";"):
                continue
            if line.startswith("#"):
                d = line[1:].strip()
                if d.startswith("ifdef ") or d.startswith("if "):
                    cond = d[3:].strip() if d.startswith("if ") else d[6:].strip()
                    val = evaluate(cond, DEFINES)
                    stack.append([val, val, active])
                    active = active and val
                elif d.startswith("ifndef "):
                    val = not evaluate(d[7:].strip(), DEFINES)
                    stack.append([val, val, active])
                    active = active and val
                elif d.startswith("else"):
                    if stack:
                        t, _, parent = stack[-1]
                        t = not t
                        stack[-1][0] = t
                        stack[-1][1] = stack[-1][1] or t
                        active = parent and t
                elif d.startswith("endif"):
                    if stack:
                        _, _, parent = stack.pop()
                        active = parent
                continue

            m = PROTO.match(line)
            if not m:
                continue
            num, aue, files, body, rest = m.groups()
            num = int(num)
            cm = CALL.search(body)
            if not cm:
                continue
            name = cm.group(1)
            if name in ("nosys",):
                continue
            if not active:
                continue
            # later definitions of the same number overwrite earlier ones
            calls[num] = (name, aue, files)

    maxn = max(calls) if calls else 0
    enum_lines = []
    table = ["NULL"] * (maxn + 1)

    # XNU reuses a handful of names across numbers (ENOSYS is defined for
    # several slots, and #if branches redefine entries). A C enum cannot hold
    # two enumerators with one name, so the canonical number keeps the bare
    # name and any later duplicate gets a _<n> suffix.
    #
    # Canonical choice: for DSYS_ENOSYS prefer 78, which is the number XNU
    # uses for "syscall not implemented" in the live table.
    seen = {}
    for n in sorted(calls):
        name, aue, files = calls[n]
        up = name.upper()
        if up in seen:
            enum_name = f"DSYS_{up}_{n}"
        else:
            enum_name = f"DSYS_{up}"
            seen[up] = n
        enum_lines.append(f"    {enum_name} = {n},")
        table[n] = '"' + name + '"'

    with open(OUT, "w") as f:
        f.write("/* GENERATED by tools/gen_syscalls.py from XNU bsd/kern/syscalls.master.\n")
        f.write(" * Do not edit. Regenerate: python3 tools/gen_syscalls.py spec/master.txt src/generated/syscalls.h\n")
        f.write(f" * {len(calls)} named calls, max number {maxn}.\n */\n")
        f.write("#ifndef DSYS_SYSCALLS_H\n#define DSYS_SYSCALLS_H\n\n")
        f.write("#include <stddef.h>  /* NULL, used by the name table */\n\n")
        f.write(f"#define DSYS_MAX_SYSCALL {maxn}\n\n")
        f.write("enum dsys_call {\n")
        f.write("\n".join(enum_lines))
        f.write("\n};\n\n")
        f.write("/* index = Darwin syscall number; NULL = unimplemented/nosys */\n")
        f.write("static const char *const dsys_table_name[DSYS_MAX_SYSCALL + 1] = {\n")
        for i in range(0, maxn + 1, 8):
            chunk = ", ".join(table[i:i + 8])
            f.write(f"    {chunk},\n")
        f.write("};\n\n")
        f.write("#endif\n")
    print(f"wrote {OUT}: {len(calls)} calls, max {maxn}")


main()
